def load_environment_from_geant4_sh(script_path: Path) -> dict[str, str]:
    command = f"source {shlex.quote(str(script_path))} >/dev/null 2>&1 && env -0"
    result = subprocess.run(
        ["bash", "-c", command],
        check=True,
        capture_output=True,
    )
    env: dict[str, str] = {}
    for entry in result.stdout.decode("utf-8", errors="replace").split("\0"):
        if not entry or "=" not in entry:
            continue
        key, value = entry.split("=", 1)
        env[key] = value
    return env


def build_runtime_environment(geant4_sh: str) -> dict[str, str]:
    runtime_env = dict(os.environ)
    if geant4_sh:
        script_path = Path(geant4_sh).expanduser().resolve()
        require_file(script_path, "Geant4 setup script")
        log(f"Loading Geant4 environment from {script_path}")
        runtime_env.update(load_environment_from_geant4_sh(script_path))
    missing = [name for name in REQUIRED_GEANT4_ENV_VARS if not runtime_env.get(name)]
    if missing:
        raise SystemExit(
            "Missing Geant4 runtime data environment variables: "
            + ", ".join(missing)
            + ". Pass --geant4-sh /path/to/geant4.sh or source geant4.sh before running."
        )
    invalid_paths: list[str] = []
    for name in REQUIRED_GEANT4_ENV_VARS:
        raw_path = runtime_env[name]
        data_path = Path(raw_path).expanduser()
        if not data_path.is_dir():
            invalid_paths.append(f"{name}={raw_path} (directory not found)")
            continue
        required_file = REQUIRED_GEANT4_DATA_FILES.get(name)
        if required_file and not (data_path / required_file).is_file():
            invalid_paths.append(f"{name}={raw_path} ({required_file} not found)")
    if invalid_paths:
        raise SystemExit(
            "Invalid Geant4 runtime data paths: "
            + "; ".join(invalid_paths)
            + "."
        )
    return runtime_env


def range_inclusive(start: float, stop: float, step: float) -> list[float]:
    values: list[float] = []
    current = start
    epsilon = step / 1000.0
    while current <= stop + epsilon:
        values.append(round(current, 10))
        current += step
    if values and values[-1] > stop + epsilon:
        values.pop()
    if not values or abs(values[-1] - stop) > epsilon:
        values.append(round(stop, 10))
    return values


def normalize_fractions(fractions: dict[str, float]) -> dict[str, float]:
    total = sum(fractions.values())
    if total <= 0.0:
        raise SystemExit("Atmosphere composition fractions are invalid.")
    return {key: value / total for key, value in fractions.items()}


def geometric_to_geopotential_km(alt_km: float) -> float:
    return (EARTH_RADIUS_GEOPOTENTIAL_KM * alt_km) / (EARTH_RADIUS_GEOPOTENTIAL_KM + alt_km)


def standard_atmosphere_state(alt_km: float) -> tuple[float, float, float]:
    geopotential_km = geometric_to_geopotential_km(alt_km)
    layer_index = len(STANDARD_ATMOSPHERE_LAYERS) - 1
    for index in range(len(STANDARD_ATMOSPHERE_LAYERS) - 1):
        if STANDARD_ATMOSPHERE_LAYERS[index][0] <= geopotential_km < STANDARD_ATMOSPHERE_LAYERS[index + 1][0]:
            layer_index = index
            break

    base_h_km, base_t, base_p, lapse = STANDARD_ATMOSPHERE_LAYERS[layer_index]
    delta_h_m = (geopotential_km - base_h_km) * 1000.0
    if abs(lapse) < 1e-12:
        temperature = base_t
        pressure = base_p * math.exp((-9.80665 * delta_h_m) / (DRY_AIR_GAS_CONSTANT * base_t))
    else:
        temperature = base_t + lapse * delta_h_m
        pressure = base_p * (base_t / temperature) ** (9.80665 / (DRY_AIR_GAS_CONSTANT * lapse))
    density_kg_m3 = pressure / (DRY_AIR_GAS_CONSTANT * temperature)
    return temperature, pressure, density_kg_m3


def datetime_to_api_string(year: int, month: int, day: int, hour_utc: float) -> str:
    base = dt.datetime(year, month, day, tzinfo=dt.timezone.utc)
    moment = base + dt.timedelta(hours=hour_utc)
    return moment.isoformat().replace("+00:00", "Z")


def http_post_json(url: str, payload: dict[str, object], retries: int = 3) -> dict[str, object]:
    body = json.dumps(payload).encode("utf-8")
    headers = {"accept": "application/json", "content-type": "application/json"}
    delays = [5, 15, 30]

    for attempt in range(retries):
        log(f"POST {url} attempt {attempt + 1}/{retries}")
        req = urllib.request.Request(url, data=body, headers=headers, method="POST")
        try:
            with urllib.request.urlopen(req, timeout=120) as response:
                log(f"POST {url} succeeded")
                return json.loads(response.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:
            if exc.code in (429, 503) and attempt + 1 < retries:
                wait_seconds = delays[min(attempt, len(delays) - 1)]
                log(f"POST {url} returned {exc.code}; waiting {wait_seconds}s before retry")
                time.sleep(delays[min(attempt, len(delays) - 1)])
                continue
            detail = exc.read().decode("utf-8", errors="replace")
            raise SystemExit(f"NRLMSIS API request failed ({exc.code}): {detail or exc.reason}") from exc
        except urllib.error.URLError as exc:
            if attempt + 1 < retries:
                wait_seconds = delays[min(attempt, len(delays) - 1)]
                log(f"POST {url} failed ({exc.reason}); waiting {wait_seconds}s before retry")
                time.sleep(delays[min(attempt, len(delays) - 1)])
                continue
            raise SystemExit(f"NRLMSIS API request failed: {exc.reason}") from exc
    raise SystemExit("NRLMSIS API request failed after retries.")


def http_get_text(url: str, retries: int = 3) -> str:
    delays = [5, 15, 30]
    for attempt in range(retries):
        log(f"GET {url} attempt {attempt + 1}/{retries}")
        try:
            with urllib.request.urlopen(url, timeout=120) as response:
                log(f"GET {url} succeeded")
                return response.read().decode("utf-8")
        except urllib.error.HTTPError as exc:
            if exc.code in (404, 429, 503) and attempt + 1 < retries:
                wait_seconds = delays[min(attempt, len(delays) - 1)]
                log(f"GET {url} returned {exc.code}; waiting {wait_seconds}s before retry")
                time.sleep(delays[min(attempt, len(delays) - 1)])
                continue
            detail = exc.read().decode("utf-8", errors="replace")
            raise SystemExit(f"Failed to download NRLMSIS output ({exc.code}): {detail or exc.reason}") from exc
        except urllib.error.URLError as exc:
            if attempt + 1 < retries:
                wait_seconds = delays[min(attempt, len(delays) - 1)]
                log(f"GET {url} failed ({exc.reason}); waiting {wait_seconds}s before retry")
                time.sleep(delays[min(attempt, len(delays) - 1)])
                continue
            raise SystemExit(f"Failed to download NRLMSIS output: {exc.reason}") from exc
    raise SystemExit("Failed to download NRLMSIS output after retries.")


def parse_api_nrlmsis_text(version: str, text: str) -> list[dict[str, float]]:
    rows: list[dict[str, float]] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        try:
            values = [float(part) for part in stripped.split()]
        except ValueError:
            continue

        if version == "NRLMSIS2.1":
            if len(values) < 19:
                continue
            rows.append(
                {
                    "height": values[5],
                    "O1": values[8],
                    "N2": values[9],
                    "O2": values[10],
                    "rho": values[12],
                    "temp": values[13],
                    "He": values[15],
                    "Ar": values[16],
                    "H": values[17],
                    "N1": values[18],
                }
            )
        else:
            if len(values) < 18:
                continue
            rows.append(
                {
                    "height": values[5],
                    "O1": values[8],
                    "N2": values[9],
                    "O2": values[10],
                    "rho": values[11],
                    "temp": values[12],
                    "He": values[14],
                    "Ar": values[15],
                    "H": values[16],
                    "N1": values[17],
                }
            )
    if not rows:
        raise SystemExit("NRLMSIS output could not be parsed.")
    return rows


def parse_legacy_nrlm_text(text: str) -> list[dict[str, float]]:
    rows: list[dict[str, float]] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        parts = stripped.split()
        try:
            values = [float(part) for part in parts]
        except ValueError:
            continue
        if len(values) < 10:
            continue
        if not (0.0 <= values[0] <= 2000.0):
            continue
        rows.append(
            {
                "height": values[0],
                "O1": values[1],
                "N2": values[2],
                "O2": values[3],
                "rho": values[4],
                "temp": values[5],
                "He": values[6],
                "Ar": values[7],
                "H": values[8],
                "N1": values[9],
            }
        )
    if not rows:
        raise SystemExit("Legacy .nrlm atmosphere text could not be parsed.")
    return rows


def parse_atmosphere_text(version: str, text: str) -> list[dict[str, float]]:
    numeric_rows: list[list[float]] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        try:
            numeric_rows.append([float(part) for part in stripped.split()])
        except ValueError:
            continue
    if not numeric_rows:
        raise SystemExit("Atmosphere text contained no numeric rows.")

    sample = numeric_rows[0]
    if len(sample) >= 18 and sample[0] > 1900:
        return parse_api_nrlmsis_text(version, text)
    if len(sample) >= 10 and 0.0 <= sample[0] <= 2000.0:
        return parse_legacy_nrlm_text(text)
    raise SystemExit("Atmosphere text format was not recognized.")


def interpolate_value(x0: float, y0: float, x1: float, y1: float, x: float, logspace: bool) -> float:
    if abs(x1 - x0) < 1e-12:
        return y0
    fraction = (x - x0) / (x1 - x0)
    if logspace and y0 > 0.0 and y1 > 0.0:
        return math.exp(math.log(y0) + fraction * (math.log(y1) - math.log(y0)))
    return y0 + fraction * (y1 - y0)


def resample_profile(rows: list[dict[str, float]], target_step: float) -> list[dict[str, float]]:
    if target_step >= 1.0:
        return rows

    target_heights = range_inclusive(rows[0]["height"], rows[-1]["height"], target_step)
    resampled: list[dict[str, float]] = []
    index = 0
    keys = ("O1", "N2", "O2", "rho", "temp", "He", "Ar", "H", "N1")

    for height in target_heights:
        while index + 1 < len(rows) and rows[index + 1]["height"] < height:
            index += 1
        left = rows[index]
        right = rows[min(index + 1, len(rows) - 1)]
        entry = {"height": height}
        for key in keys:
            entry[key] = interpolate_value(
                left["height"],
                left[key],
                right["height"],
                right[key],
                height,
                logspace=(key != "temp"),
            )
        resampled.append(entry)
    return resampled


def load_nrlmsis_rows_from_text(args: argparse.Namespace, raw_text: str, simdir: Path) -> list[dict[str, float]]:
    rows = parse_atmosphere_text(args.version, raw_text)
    resampled = resample_profile(rows, args.alt_step)
    log(f"Parsed {len(rows)} atmosphere rows; using {len(resampled)} rows after resampling")
    return resampled


def build_fixed_atmosphere_profile(args: argparse.Namespace, simdir: Path) -> list[dict[str, float]]:
    log(
        "Building deterministic built-in atmosphere for "
        f"alt={args.alt_min}..{args.alt_max} km step={args.alt_step} km"
    )
    fractions = normalize_fractions(STANDARD_AIR_FRACTIONS)
    rows: list[dict[str, float]] = []
    summary_lines = ["# altitude_km temperature_K pressure_Pa density_kg_m3 N2_cm-3 O2_cm-3 Ar_cm-3 He_cm-3"]
    for alt_km in range_inclusive(args.alt_min, args.alt_max, args.alt_step):
        temperature, pressure, density_kg_m3 = standard_atmosphere_state(alt_km)
        total_number_density_cm3 = pressure / (BOLTZMANN * temperature) / 1_000_000.0
        row = {
            "height": alt_km,
            "O1": 0.0,
            "N2": total_number_density_cm3 * fractions["N2"],
            "O2": total_number_density_cm3 * fractions["O2"],
            "rho": density_kg_m3 * 0.001,
            "temp": temperature,
            "He": total_number_density_cm3 * fractions["He"],
            "Ar": total_number_density_cm3 * fractions["Ar"],
            "H": total_number_density_cm3 * fractions["H"],
            "N1": 0.0,
        }
        rows.append(row)
        summary_lines.append(
            "{alt:.3f} {temp:.6f} {press:.9e} {rho:.9e} {n2:.9e} {o2:.9e} {ar:.9e} {he:.9e}".format(
                alt=alt_km,
                temp=temperature,
                press=pressure,
                rho=density_kg_m3,
                n2=row["N2"],
                o2=row["O2"],
                ar=row["Ar"],
                he=row["He"],
            )
        )
    (simdir / "simulation.fixed_atmosphere.txt").write_text("\n".join(summary_lines) + "\n", encoding="utf-8")
    log(f"Wrote {simdir / 'simulation.fixed_atmosphere.txt'}")
    log(f"Built {len(rows)} deterministic atmosphere rows")
    return rows


def fetch_atmosphere_profile(args: argparse.Namespace, simdir: Path) -> list[dict[str, float]]:
    api_step = max(args.alt_step, 1.0)
    log(
        "Preparing NRLMSIS request for "
        f"lat={args.latitude_deg}, lon={args.longitude_deg}, "
        f"date={args.year:04d}-{args.month:02d}-{args.day:02d} hour={args.hour_utc:.2f}, "
        f"alt={args.alt_min}..{args.alt_max} km step={args.alt_step} km"
    )
    payload: dict[str, object] = {
        "version": args.version,
        "timeType": "ut",
        "coordinateType": "geo",
        "datetime": datetime_to_api_string(args.year, args.month, args.day, args.hour_utc),
        "lat": args.latitude_deg,
        "lon": args.longitude_deg,
        "height": args.alt_max,
        "profileType": 1,
        "start": args.alt_min,
        "stop": args.alt_max,
        "step": api_step,
        "fdaily": -1,
        "f3month": -1,
        "ap": -1,
    }

    try:
        response = http_post_json("https://kauai.ccmc.gsfc.nasa.gov/instantrun/api/nrlmsis/", payload)
    except SystemExit as exc:
        cached_txt = simdir / "simulation.nrlmsis.txt"
        if "429" in str(exc) and cached_txt.is_file():
            log(f"NASA rate-limited the request; reusing cached {cached_txt}")
            return load_nrlmsis_rows_from_text(args, cached_txt.read_text(encoding="utf-8"), simdir)
        raise

    txt_url = response.get("txt")
    if not isinstance(txt_url, str) or not txt_url:
        raise SystemExit(f"Unexpected NRLMSIS API response: {response}")

    log(f"Downloading raw atmosphere table from {txt_url}")
    raw_text = http_get_text(txt_url)
    (simdir / "simulation.nrlmsis.txt").write_text(raw_text, encoding="utf-8")
    return load_nrlmsis_rows_from_text(args, raw_text, simdir)


def write_psf(rows: list[dict[str, float]], psf_path: Path) -> None:
    if len(rows) < 2:
        raise SystemExit("Need at least two atmosphere rows to write simulation.psf.")

    log(f"Writing {psf_path.name} with {len(rows)} atmosphere layers")
    earth_radius_m = 6_371_000.0
    kb = 1.38064852e-23
    u = 1.66054e-24
    cr_km = 20.0 / 1000.0
    formatstring = "%e %e %e %e %e %e %i %e %e %e %e %e %e %e %e %e"

    lines: list[str] = []
    lines.append("#O478Si284Al84Fe52Ca37Na28Mg15 N O Ar He H")

    er_km = earth_radius_m / 1000.0
    t = 293.15
    p = 101325.0
    d = 2.7
    lines.append(formatstring % (0, er_km - cr_km, 0, 2 * math.pi, 0, math.pi, 0, t, d, p, 1.0, 0, 0, 0, 0, 0))
    lines.append(formatstring % (er_km - cr_km, er_km, 0, 2 * math.pi, 0, math.pi, 1, t, d, p, 1.0, 0, 0, 0, 0, 0))

    thicknesses_km = [rows[i + 1]["height"] - rows[i]["height"] for i in range(len(rows) - 1)]
    thicknesses_km.append(thicknesses_km[-1])

    for index, row in enumerate(rows):
        alt = row["height"]
        temp = row["temp"]
        rho = row["rho"]
        n_n2 = row["N2"] + 0.5 * row["N1"]
        n_o2 = row["O2"] + 0.5 * row["O1"]
        n_he = row["He"]
        n_ar = row["Ar"]
        n_h = row["H"]

        p_o2 = n_o2 * kb * 1_000_000.0 * temp
        p_n2 = n_n2 * kb * 1_000_000.0 * temp
        p_ar = n_ar * kb * 1_000_000.0 * temp
        p_he = n_he * kb * 1_000_000.0 * temp
        p_h = n_h * kb * 1_000_000.0 * temp
        p_total = p_o2 + p_n2 + p_ar + p_he + p_h

        m_o2 = n_o2 * (2 * 15.9994) * u
        m_n2 = n_n2 * (2 * 14.0067) * u
        m_ar = n_ar * 39.948 * u
        m_he = n_he * 4.0026 * u
        m_h = n_h * 1.008 * u
        total_mass = m_o2 + m_n2 + m_ar + m_he + m_h
        if total_mass <= 0.0:
            raise SystemExit("Atmosphere row has non-positive mass; cannot build simulation.psf.")

        mf_n2 = m_n2 / total_mass
        mf_o2 = m_o2 / total_mass
        mf_ar = m_ar / total_mass
        mf_he = m_he / total_mass
        mf_h = m_h / total_mass

        bottom_km = earth_radius_m / 1000.0 + alt
        top_km = bottom_km + thicknesses_km[index]
        sdid = index + 2

        lines.append(
            formatstring
            % (
                bottom_km,
                top_km,
                0,
                2 * math.pi,
                0,
                math.pi,
                sdid,
                temp,
                rho,
                p_total,
                0,
                mf_n2,
                mf_o2,
                mf_ar,
                mf_he,
                mf_h,
            )
        )

    top_km = earth_radius_m / 1000.0 + rows[-1]["height"] + thicknesses_km[-1]
    lines.append(formatstring % (top_km, top_km + cr_km, 0, 2 * math.pi, 0, math.pi, len(rows) + 2, t, d, p, 1.0, 0, 0, 0, 0, 0))
    psf_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log(f"Wrote {psf_path}")


def parse_formula(formula: str) -> dict[str, dict[str, float | str]]:
    result: dict[str, dict[str, float | str]] = {}
    total = 0.0
    for element, number in re.findall(r"([A-Z][a-z]*)(\d*)", formula):
        mass_fraction = float(number or "0") / 1000.0
        result[element] = {"mass fraction": mass_fraction, "material": element}
        total += mass_fraction
    if total <= 0.0:
        raise SystemExit(f"Could not parse core formula: {formula}")
    if abs(total - 1.0) > 1e-4:
        factor = 1.0 / total
        for element in result:
            result[element]["mass fraction"] = float(result[element]["mass fraction"]) * factor
    return result


def parse_psf_header(psf_path: Path) -> tuple[dict[str, dict[str, float | str]], dict[str, dict[str, int | float | str]]]:
    header = psf_path.read_text(encoding="utf-8").splitlines()[0].split()
    core = parse_formula(header[0].lstrip("#"))
    template: dict[str, dict[str, int | float | str]] = {}
    for index, material in enumerate(header[1:]):
        template[material] = {"mass fraction": 0.0, "material": material, "colidx": index}
    return core, template


def gdml_material(mat: dict[str, dict[str, float | str]], name: str, temperature: float, density: float, pressure: float, state: str) -> str:
    output = [f'\t<material name="{name}" state="{state}">']
    output.append(f'\t\t<D value="{density:e}" unit="g/cm3" />')
    output.append(f'\t\t<T value="{temperature:e}" unit="K" />')
    output.append(f'\t\t<P value="{pressure:e}" unit="Pa" />')
    for entry in mat.values():
        fraction = float(entry["mass fraction"])
        material = str(entry["material"])
        if fraction != 0.0:
            output.append(f'\t\t<fraction n="{fraction:e}" ref="G4_{material}" />')
    output.append("\t</material>")
    return "\n".join(output) + "\n"


def read_numeric_psf(psf_path: Path) -> list[list[float]]:
    rows: list[list[float]] = []
    for line in psf_path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        rows.append([float(part) for part in stripped.split()])
    return rows


def psf_to_gdml(rootdir: Path, psf_path: Path, gdml_path: Path) -> None:
    log(f"Converting {psf_path.name} to {gdml_path.name}")
    core, template = parse_psf_header(psf_path)
    rows = read_numeric_psf(psf_path)
    materials: list[str] = []
    geometry: list[str] = []
    structure: list[tuple[str, str, str, int]] = []

    for row in rows:
        sdid = int(row[6])
        material_name = f"material{sdid}"
        solid_name = f"solid{sdid}"
        is_core = row[10] == 1.0
        if is_core:
            materials.append(gdml_material(core, material_name, row[7], row[8], row[9], "solid"))
        else:
            atmosphere: dict[str, dict[str, float | str]] = {}
            for material, entry in template.items():
                atmosphere[material] = {
                    "material": material,
                    "mass fraction": row[int(entry["colidx"]) + 11],
                }
            materials.append(gdml_material(atmosphere, material_name, row[7], row[8], row[9], "gas"))

        delta_phi = row[3] - row[2]
        delta_theta = row[5] - row[4]
        delta_phi_text = "TWOPI" if abs(delta_phi - 2.0 * math.pi) < 0.01 else f"{delta_phi}"
        delta_theta_text = "PI" if abs(delta_theta - math.pi) < 0.01 else f"{delta_theta}"
        geometry.append(
            '\t<sphere name="{name}" rmin="{rmin:f}" rmax="{rmax:f}" startphi="{startphi:.4f}" deltaphi="{dphi}" '
            'starttheta="{starttheta:.4f}" deltatheta="{dtheta}" lunit="km" aunit="rad"/>\n'.format(
                name=solid_name,
                rmin=row[0],
                rmax=row[1],
                startphi=row[2],
                dphi=delta_phi_text,
                starttheta=row[4],
                dtheta=delta_theta_text,
            )
        )
        structure.append((f"volume{sdid}", material_name, solid_name, sdid))

    world = rows[-1][1] + 100.0
    attris_materials = (rootdir / "atris" / "interface" / "atris.materials").read_text(encoding="utf-8")

    pieces = [
        # Avoid remote schema validation on batch nodes; Geant4 can parse the GDML without it.
        '<?xml version="1.0" encoding="UTF-8" standalone="no" ?>\n<gdml>\n\n',
        '<define>\n\t<constant name="PI" value="1.*pi"/>\n\t<constant name="TWOPI" value="2.*pi"/>'
        '\n\t<position name="center"/>\n\t<rotation name="identity"/>\n</define>\n',
        "<materials>\n",
        attris_materials,
    ]
    pieces.extend(materials)
    pieces.append("</materials>\n")
    pieces.append("<solids>\n")
    pieces.append(f'\t<box name="WorldBox" x="{world * 2:f}" y="{world * 2:f}" z="{world * 2:f}" lunit="km"/>\n')
    pieces.extend(geometry)
    pieces.append("</solids>\n")
    pieces.append("<structure>\n")
    for volume_name, material_name, solid_name, sdid in structure:
        pieces.append(
            '\t<volume name="{volume}">\n\t\t<materialref ref="{material}"/>\n\t\t<solidref ref="{solid}"/>'
            '\n\t\t<auxiliary auxtype="SensDet" auxvalue="{sdid}"/>\n\t</volume>\n'.format(
                volume=volume_name,
                material=material_name,
                solid=solid_name,
                sdid=sdid,
            )
        )
    pieces.append('\t<volume name="World">\n\t\t<materialref ref="Vacuum"/>\n\t\t<solidref ref="WorldBox"/>\n')
    for volume_name, _, _, _ in structure:
        pieces.append(
            '\t\t<physvol>\n\t\t\t<volumeref ref="{volume}"/>\n\t\t\t<positionref ref="center"/>'
            '\n\t\t</physvol>\n'.format(volume=volume_name)
        )
    pieces.append("\t</volume>\n</structure>\n")
    pieces.append('<setup name="Exoplanet" version="1.0">\n\t<world ref="World"/>\n</setup>\n</gdml>\n')
    gdml_path.write_text("".join(pieces), encoding="utf-8")
    log(f"Wrote {gdml_path}")


def numeric_rows(path: Path) -> list[list[float]]:
    rows: list[list[float]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            parts = line.split()
            if len(parts) < 2:
                continue
            try:
                rows.append([float(parts[0]), float(parts[1])])
            except ValueError:
                continue
    return rows


def radius_from_psf(psf_path: Path) -> float:
    rows = numeric_rows(psf_path)
    if len(rows) < 2:
        raise SystemExit(f"Could not parse enough numeric rows from {psf_path}")
    return rows[-2][1] + 0.001


def logspace_powers(start: float, stop: float, count: int) -> list[float]:
    if count < 2:
        return [10**start]
    step = (stop - start) / (count - 1)
    return [10 ** (start + step * index) for index in range(count)]


def write_bins(path: Path, values: list[float]) -> None:
    with path.open("w", encoding="utf-8") as handle:
        for value in values:
            handle.write(f"{value:.9f}\n")


def write_macro(path: Path, bins: list[float], radius_km: float, particle: str, threads: int, event_count: int) -> None:
    seed1 = random.randint(31, 999999)
    seed2 = random.randint(31, 999999)
    progress_modulo = max(1, event_count // 100)
    lines = [
        f"/run/numberOfThreads {threads}",
        "/control/cout/useBuffer false",
        "/run/initialize",
        "/run/verbose 2",
        f"/run/printProgress {progress_modulo}",
        f"/gps/particle {particle}",
        "/gps/ene/type User",
        "/gps/hist/type energy",
        f"/gps/hist/point {bins[0]:.9f} 0.000000000",
    ]
    if threads > 1:
        lines.insert(1, "/control/cout/ignoreThreadsExcept 0")
    for value in bins[1:]:
        lines.append(f"/gps/hist/point {value:.9f} 1.000000000")
    lines.extend(
        [
            "/gps/pos/type Surface",
            "/gps/pos/shape Sphere",
            "/gps/pos/centre 0 0 0 m",
            f"/gps/pos/radius {radius_km:.3f} km",
            "/gps/ang/type cos",
            "/gps/ang/mintheta 0 deg",
            "/gps/ang/maxtheta 90 deg",
            "/gps/number 1",
            "/run/setCut 100. m",
            "/run/particle/dumpCutValues",
            f"/random/setSeeds {seed1} {seed2}",
            f"/run/beamOn {event_count}",
        ]
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def copy_phantoms(rootdir: Path, simdir: Path) -> None:
    phantom_dir = rootdir / "phantoms"
    if not phantom_dir.is_dir():
        raise SystemExit(f"Missing phantom directory: {phantom_dir}")
    log(f"Copying phantom files from {phantom_dir} to {simdir}")
    for path in phantom_dir.iterdir():
        if path.is_file():
            shutil.copy2(path, simdir / path.name)
    log("Copied phantom files")


def generate_macros(simdir: Path, numberparts: int, threads: int, alpha_factor: float) -> dict[str, int]:
    log(
        f"Generating macro and bin files with numberparts={numberparts}, "
        f"threads={threads}, alpha_factor={alpha_factor}"
    )
    radius_km = radius_from_psf(simdir / "simulation.psf")
    base_bins = logspace_powers(0.0, 6.0, 121)
    proton_events = len(base_bins) * numberparts
    alpha_events = len(base_bins) * int(numberparts * alpha_factor)

    shutil.copy2(simdir / "simulation.gdml", simdir / "protons.gdml")
    shutil.copy2(simdir / "simulation.gdml", simdir / "alphas.gdml")
    write_bins(simdir / "protons.bins", base_bins)
    write_bins(simdir / "alphas.bins", [value * 4.0 for value in base_bins])
    write_macro(simdir / "protons.mac", base_bins, radius_km, "proton", threads, proton_events)
    write_macro(simdir / "alphas.mac", [value * 4.0 for value in base_bins], radius_km, "alpha", threads, alpha_events)
    log("Generated protons/alphas macro and bin files")
    return {"protons": proton_events, "alphas": alpha_events}


def prepare_geometry(args: argparse.Namespace, rootdir: Path, simdir: Path) -> None:
    log("Starting geometry preparation")
    if args.atmosphere_source == "fixed":
        rows = build_fixed_atmosphere_profile(args, simdir)
    elif args.atmosphere_source == "file":
        if not args.nrlmsis_txt:
            raise SystemExit("--atmosphere-source=file requires --nrlmsis-txt")
        txt_path = Path(args.nrlmsis_txt).expanduser().resolve()
        require_file(txt_path, "NRLMSIS text file")
        log(f"Using local NRLMSIS text file {txt_path}")
        raw_text = txt_path.read_text(encoding="utf-8")
        (simdir / "simulation.nrlmsis.txt").write_text(raw_text, encoding="utf-8")
        rows = load_nrlmsis_rows_from_text(args, raw_text, simdir)
    else:
        log("Using live NASA NRLMSIS fetch")
        rows = fetch_atmosphere_profile(args, simdir)
    write_psf(rows, simdir / "simulation.psf")
    psf_to_gdml(rootdir, simdir / "simulation.psf", simdir / "simulation.gdml")
    log("Geometry preparation complete")


def should_report_phantom_progress(phantom_index: int, phantom_count: int) -> bool:
    if phantom_count <= 8:
        return True
    checkpoints = {0, phantom_count - 1}
    step = max(1, phantom_count // 4)
    checkpoints.update(range(step - 1, phantom_count, step))
    return phantom_index in checkpoints


def should_echo_atris_line(line: str) -> bool:
    stripped = line.strip()
    if not stripped:
        return False
    if stripped.startswith(("-------- EEEE", "***", "Backtrace:", "[PID=", ": Aborted")):
        return True
    keywords = (
        "G4Exception",
        "Fatal Exception",
        "CAUGHT SIGNAL",
        "Traceback",
        "Error",
        "ERROR",
        "Warning",
        "WARNING",
        "Aborted",
        "SIGABRT",
    )
    if any(keyword in stripped for keyword in keywords):
        return True
    important_prefixes = (
        "### Incorrect use!",
        "### AtRIS: proceeding to load ",
        "### AtRIS: nrofdetectors has been determined",
        "### AtRIS: Generating detbins",
        "### AtRIS: read ",
        "### AtRIS: Starting the simulation",
        "### AtRIS: the simulation has completed",
        "### AtRIS: The logfile has been sucessfully closed",
        "### AtRIS: opening file:",
    )
    return stripped.startswith(important_prefixes)


def extract_atris_progress_event(line: str) -> int | None:
    stripped = line.strip()
    if ATRIS_DIRECT_PROGRESS_RE.match(stripped):
        match = re.search(r"event\s+(?P<event>\d+)\b", stripped)
        if match:
            return int(match.group("event"))
        return None
    match = ATRIS_EVENT_PROGRESS_RE.match(stripped)
    if match:
        return int(match.group("event"))
    geant_match = GEANT4_EVENT_START_RE.search(stripped)
    if geant_match:
        return int(geant_match.group("event"))
    return None


def format_atris_progress(line: str, total_events: int | None = None) -> str | None:
    stripped = line.strip()
    if ATRIS_DIRECT_PROGRESS_RE.match(stripped):
        event = extract_atris_progress_event(stripped)
        if event is None:
            return stripped
        if total_events:
            fraction = min(max(event / total_events, 0.0), 1.0)
            return f"AtRIS progress: event {event}/{total_events} ({fraction:.1%})"
        return f"AtRIS progress: event {event}"
    match = ATRIS_EVENT_PROGRESS_RE.match(stripped)
    if not match:
        geant_match = GEANT4_EVENT_START_RE.search(stripped)
        if not geant_match:
            return None
        event = int(geant_match.group("event"))
        if total_events:
            fraction = min(max(event / total_events, 0.0), 1.0)
            return f"AtRIS progress: event {event}/{total_events} ({fraction:.1%})"
        return f"AtRIS progress: event {event}"
    event = int(match.group("event"))
    if total_events:
        fraction = min(max(event / total_events, 0.0), 1.0)
        prefix = f"AtRIS progress: event {event}/{total_events} ({fraction:.1%})"
    else:
        prefix = f"AtRIS progress: event {event}"
    return f"{prefix}, elapsed {match.group('elapsed')}s, {match.group('speed')} primaries/s"


def enqueue_stream_lines(stream: object, queue: Queue[str | None]) -> None:
    try:
        for line in stream:
            queue.put(line)
    finally:
        queue.put(None)


def run_atris(
    simdir: Path,
    runtime_env: dict[str, str],
    phys_list: str,
    simname: str,
    phantom_count: int,
    atris_console: str,
    total_events: int | None = None,
) -> None:
    command = ["./AtRIS", phys_list, simname, "-1", str(phantom_count)]
    log_path = simdir / f"{simname}.log"
    log(
        f"Starting AtRIS run for {simname}; full raw output will be written to {log_path.name} "
        f"(console mode: {atris_console})"
    )
    phantom_load_started = False
    gdml_validation_count = 0
    simulation_started = False
    simulation_start_time: float | None = None
    last_visible_output_time = time.monotonic()
    last_status_time = 0.0
    last_status_log_size = 0
    max_progress_event_seen = -1

    def emit_summary_log(message: str, timestamp: float | None = None) -> None:
        nonlocal last_visible_output_time
        log(message)
        last_visible_output_time = time.monotonic() if timestamp is None else timestamp

    with log_path.open("w", encoding="utf-8", buffering=1) as handle:
        process = subprocess.Popen(
            command,
            cwd=simdir,
            env=runtime_env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
        )
        assert process.stdout is not None
        queue: Queue[str | None] = Queue()
        reader = threading.Thread(target=enqueue_stream_lines, args=(process.stdout, queue), daemon=True)
        reader.start()
        while True:
            try:
                queued_line = queue.get(timeout=1.0)
            except Empty:
                now = time.monotonic()
                if (
                    atris_console == "summary"
                    and simulation_started
                    and process.poll() is None
                    and now - last_status_time >= ATRIS_STATUS_SECONDS
                ):
                    try:
                        log_size = log_path.stat().st_size
                    except OSError:
                        log_size = 0
                    elapsed = int(now - simulation_start_time) if simulation_start_time is not None else 0
                    message = f"AtRIS running: {elapsed:>4}s elapsed; {log_path.name} is {log_size} bytes"
                    emit_summary_log(message, now)
                    last_status_time = now
                    last_status_log_size = log_size
                continue
            if queued_line is None:
                break
            line = queued_line
            now = time.monotonic()
            handle.write(line)
            handle.flush()
            if atris_console == "full":
                print(line, end="", flush=True)
                continue
            stripped = line.strip()
            match = ATRIS_PHANTOM_LOAD_RE.match(stripped)
            if match:
                phantom_index = int(match.group(2))
                if not phantom_load_started:
                    emit_summary_log("AtRIS is loading phantom response files", now)
                    phantom_load_started = True
                if match.group(1) == "radiation" and should_report_phantom_progress(phantom_index, phantom_count):
                    emit_summary_log(f"Phantom response load progress: {phantom_index + 1}/{phantom_count}", now)
                continue
            if stripped.startswith(GDML_VALIDATION_PREFIX):
                gdml_validation_count += 1
                if atris_console == "summary" and gdml_validation_count == 1:
                    emit_summary_log(
                        f"Geant4 is reporting GDML schema validation warnings; raw details are in {log_path.name}",
                        now,
                    )
                continue
            if atris_console == "summary" and stripped == "### AtRIS: Starting the simulation":
                simulation_started = True
                simulation_start_time = now
                last_status_time = now
                try:
                    last_status_log_size = log_path.stat().st_size
                except OSError:
                    last_status_log_size = 0
                if gdml_validation_count:
                    emit_summary_log(
                        f"Suppressed {gdml_validation_count} GDML validation warning lines from the terminal",
                        now,
                    )
                emit_summary_log(f"AtRIS entered the simulation phase; raw output is streaming to {log_path.name}", now)
            if atris_console == "summary":
                progress_event = extract_atris_progress_event(line)
                if progress_event is not None and progress_event <= max_progress_event_seen:
                    continue
                progress_message = format_atris_progress(line, total_events)
                if progress_message:
                    if progress_event is not None:
                        max_progress_event_seen = progress_event
                    emit_summary_log(progress_message, now)
                    continue
            if atris_console == "summary" and should_echo_atris_line(line):
                print(line, end="", flush=True)
                last_visible_output_time = now
        reader.join(timeout=1.0)
        return_code = process.wait()
    if return_code != 0:
        raise subprocess.CalledProcessError(return_code, command)
    log(f"Finished AtRIS run for {simname}")


def main() -> int:
    args = apply_run_profile(parse_args())
    rootdir = Path(args.rootdir).expanduser().resolve()
    simdir = rootdir / "atris" / "simulation"
    runtime_env: dict[str, str] | None = None

    log(f"Root directory: {rootdir}")
    log(f"Simulation directory: {simdir}")
    log(
        "Run settings: "
        f"profile={args.run_profile}, particles={args.particles}, "
        f"numberparts={args.numberparts}, phantom_count={args.phantom_count}, threads={args.threads}"
    )

    if not args.prepare_only:
        require_executable(simdir / "AtRIS", "AtRIS executable")
        runtime_env = build_runtime_environment(args.geant4_sh)

    if args.skip_prepare:
        log("Skipping geometry preparation and reusing existing simulation.psf/simulation.gdml")
        require_file(simdir / "simulation.psf", "simulation.psf")
        require_file(simdir / "simulation.gdml", "simulation.gdml")
    else:
        prepare_geometry(args, rootdir, simdir)

    if args.prepare_only:
        log("Prepare-only mode requested; not running AtRIS")
        return 0

    assert runtime_env is not None
    copy_phantoms(rootdir, simdir)
    event_counts = generate_macros(simdir, args.numberparts, args.threads, args.alpha_factor)

    run_order = {
        "protons": ("protons",),
        "alphas": ("alphas",),
        "both": ("protons", "alphas"),
    }[args.particles]
    log(f"Run order: {', '.join(run_order)}")
    for simname in run_order:
        run_atris(
            simdir,
            runtime_env,
            args.phys_list,
            simname,
            args.phantom_count,
            args.atris_console,
            event_counts.get(simname),
        )

    log("Finished")
    return 0


if __name__ == "__main__":
    sys.exit(main())
